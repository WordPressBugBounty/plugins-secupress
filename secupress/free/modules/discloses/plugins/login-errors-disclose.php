add_filter( 'authenticate', 'secupress_replace_login_errors_disclose', 21 );
add_filter( 'registration_errors', 'secupress_replace_login_errors_disclose', 1 );
add_filter( 'user_profile_update_errors', 'secupress_replace_login_errors_disclose', 1 );
add_filter( 'login_errors', 'secupress_replace_login_errors_disclose', 1 );
/**
 * Replace all login errors with a more generic message.
 *
 * @author Julio Potier
 * @since 2.7.2 Do not replace nor empty the login on failed authentication: WordPress only prefills the field when the error code is incorrect_password.
 * @since 2.2.6 Back to 1.4.6 style with new keys and default message + 1 new hook filters
 * @since 2.0 Just return the default SP message
 * @since 1.4.6 Remove "\n" from pattern + new $default value
 * @author Grégory Viguier
 * @since 1.0
 *
 * @return (WP_Error|mixed)
 */
function secupress_replace_login_errors_disclose( $wp_errors ) {
	if ( ! is_wp_error( $wp_errors ) || ! isset( $wp_errors->errors ) ) {
		return $wp_errors; // Not errors here!
	}
	$ar_keys = array_flip( array_keys( secupress_login_errors_disclose_get_messages( false ) ) );
	if ( 'authenticate' === current_filter() ) {
		unset( $ar_keys['invalid_username'], $ar_keys['invalid_email'], $ar_keys['incorrect_password'] );
	}
	$default = [	'authenticate'               => [ __( 'Authentication failed.', 'secupress' ) ],
					'registration_errors'        => [ __( 'Something went wrong.', 'secupress' ) ],
					'user_profile_update_errors' => [ __( 'Incorrect data provided. Unable to proceed.', 'secupress' ) ],
					'login_errors'               => [ __( 'Something went wrong.', 'secupress' ) ],
				];
	foreach ( $wp_errors->errors as $key => &$wp_error ) {
		if ( isset( $ar_keys[ $key ] ) ) {
			$wp_error = $default[ current_filter() ];
		}
	}
	return $wp_errors;
}

add_filter( 'wp_login_errors', 'secupress_login_errors_unknown_as_incorrect_password' );
/**
 * Pretend unknown logins failed because of a wrong password, like WordPress does for existing accounts.
 * wp-login.php only puts $_POST['log'] back in the form when the error code is incorrect_password or empty_password.
 *
 * @since 2.7.2
 * @author Julio Potier
 * @see wp-login.php
 *
 * @param (WP_Error) $errors WP Error object.
 *
 * @return (WP_Error)
 */
function secupress_login_errors_unknown_as_incorrect_password( $errors ) {
	if ( ! is_wp_error( $errors ) ) {
		return $errors;
	}

	$codes = array_flip( $errors->get_error_codes() );
	if ( ! isset( $codes['invalid_username'] ) && ! isset( $codes['invalid_email'] ) ) {
		return $errors;
	}

	$login = '';
	if ( isset( $_POST['log'] ) && is_string( $_POST['log'] ) ) { // WPCS: CSRF ok.
		$login = wp_unslash( $_POST['log'] );
	}

	$errors->remove( 'invalid_username' );
	$errors->remove( 'invalid_email' );
	$errors->add( 'incorrect_password', secupress_login_errors_get_incorrect_password_message( $login ) );

	return $errors;
}

/**
 * Build the same "incorrect password" message as WordPress core.
 *
 * @since 2.7.2
 * @author Julio Potier
 * @see wp_authenticate_username_password()
 * @see wp_authenticate_email_password()
 *
 * @param (string) $login Username or email address.
 *
 * @return (string)
 */
function secupress_login_errors_get_incorrect_password_message( $login ) {
	$escaped = '<strong>' . esc_html( $login ) . '</strong>';
	$lost    = ' <a href="' . wp_lostpassword_url() . '">' . __( 'Lost your password?' ) . '</a>';

	if ( is_email( $login ) ) {
		return sprintf(
			/* translators: %s: Email address. */
			__( '<strong>Error:</strong> The password you entered for the email address %s is incorrect.' ),
			$escaped
		) . $lost;
	}

	return sprintf(
		/* translators: %s: User name. */
		__( '<strong>Error:</strong> The password you entered for the username %s is incorrect.' ),
		$escaped
	) . $lost;
}

add_filter( 'lostpassword_errors', 'secupress_lostpassword_hide_unknown_user', 100, 2 );
/**
 * Pretend a lost password request for an unknown login succeeded, like WordPress does when the account exists.
 * retrieve_password() adds invalidcombo after this filter when no user is found, so we redirect instead of returning.
 *
 * @since 2.7.2
 * @author Julio Potier
 * @see retrieve_password()
 *
 * @param (WP_Error)      $errors    Errors generated by the reset request.
 * @param (WP_User|false) $user_data User if found, false otherwise.
 *
 * @return (WP_Error)
 */
function secupress_lostpassword_hide_unknown_user( $errors, $user_data ) {
	if ( secupress_is_user( $user_data ) ) {
		return $errors;
	}

	$action = isset( $_REQUEST['action'] ) ? $_REQUEST['action'] : ''; // WPCS: CSRF ok.
	if ( 'lostpassword' !== $action && 'retrievepassword' !== $action ) {
		return $errors;
	}

	$codes = $errors->get_error_codes();
	if ( in_array( 'empty_username', $codes, true ) ) {
		return $errors;
	}

	$other = array_diff( $codes, [ 'invalid_email', 'invalidcombo' ] );
	if ( $other ) {
		return $errors;
	}

	$redirect_to = ! empty( $_REQUEST['redirect_to'] ) ? $_REQUEST['redirect_to'] : add_query_arg( 'checkemail', 'confirm', wp_login_url() ); // WPCS: CSRF ok.
	wp_safe_redirect( $redirect_to );
	exit;
}

add_filter( 'wp_login_errors', 'secupress_login_errors_confirm_message' );
/**
 * Use a non-disclosing confirmation message after a lost password request.
 *
 * @since 2.7.2
 * @author Julio Potier
 * @see wp-login.php
 *
 * @param (WP_Error) $errors WP Error object.
 *
 * @return (WP_Error)
 */
function secupress_login_errors_confirm_message( $errors ) {
	if ( ! is_wp_error( $errors ) || ! isset( $_GET['checkemail'] ) || 'confirm' !== $_GET['checkemail'] ) { // WPCS: CSRF ok.
		return $errors;
	}

	if ( 'confirm' !== $errors->get_error_code() ) {
		return $errors;
	}

	$errors->remove( 'confirm' );
	$errors->add(
		'confirm',
		sprintf(
			/* translators: %s: Link to the login page. */
			__( 'If this username exists, you will receive the confirmation link by email, then visit the <a href="%s">login page</a>.', 'secupress' ),
			esc_url( wp_login_url() )
		),
		'message'
	);

	return $errors;
}

